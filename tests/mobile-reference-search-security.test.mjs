import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL('../'+path,import.meta.url),'utf8');
test('receipt and void lookup GET are independently scoped by tenant + tab and reject broad queries',()=>{
 const r=read('app/api/mobile/orgs/[org]/reference-search/route.ts');
 assert.match(r,/requireMobileOfficer\(req, slug, kind === 'void' \? 'tab-void' : 'tab-payment'\)/);
 assert.match(r,/q.length < 3 \|\| q.length > 80/);
 assert.match(r,/organizationId: org.id/);
 assert.match(r,/take: 121/);
 assert.match(r,/matching.length > 120/);
 assert.match(r,/take: 1001/);
 assert.match(r,/allocations.length > 1000/);
 assert.match(r,/baseOfficialReceiptNumber\(row.orNumber\)/);
 assert.match(r,/buildIssuedReceipts\(allocations\)/);
 assert.match(r,/status: r.status/);
 assert.match(r,/amountPesos: r.total/);
 assert.match(r,/scope: 'tenant_all_periods'/);
 assert.doesNotMatch(r,/export const POST|export const PATCH|export const DELETE|prisma\.\w+\.(create|update|delete|upsert)\(/);
});
test('native reference screen searches reactively and hides restricted tabs',()=>{
 const ui=read('mobile/src/app/(officer)/reference-search.tsx');
 const layout=read('mobile/src/app/(officer)/_layout.tsx');
 const home=read('mobile/src/app/(officer)/home.tsx');
 const client=read('mobile/src/api/http.ts');
 assert.match(ui,/setTimeout\(\(\) =>/);
 assert.match(ui,/, 450\)/);
 assert.match(ui,/can\('tab-payment'\)/);
 assert.match(ui,/can\('tab-void'\)/);
 assert.match(ui,/api.searchReceiptReferences\(/);
 assert.match(ui,/api.searchVoidReferences\(/);
 assert.match(ui,/maxLength=\{80\}/);
 assert.match(ui,/accessibilityLabel="Clear reference search"/);
 assert.match(ui,/setQuery\(''\)/);
 assert.match(ui,/response\?\.kind==='receipts'/);
 assert.match(ui,/response\?\.kind==='void'/);
 assert.match(layout,/Tabs.Protected guard=\{can\('tab-payment'\) \|\| can\('tab-void'\)\}/);
 assert.match(home,/router.push\(\{ pathname: '\/reference-search'/);
 assert.match(client,/kind: 'receipts'/);
 assert.match(client,/kind: 'void'/);
 assert.doesNotMatch(ui,/recordPayment\(|verifyRemittance\(|invalidateRemittance\(|submitProof\(/);
});
