#!/usr/bin/env node
// Generates typed design tokens and icon path data from their sources.
//
//   design/tokens.json            -> src/theme/tokens.ts  (copied from the CLEAR Mobile design system)
//   node_modules/bootstrap-icons  -> src/components/ui/icon-data.ts
//
// Run after changing either source: `npm run design`.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'design/tokens.json'), 'utf8'));

// ---------------------------------------------------------------- colors
const themeIds = tokens.color.themes.map((t) => t.id);
const byName = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t]));

function resolve(name, theme, depth = 0) {
  const tok = byName[name];
  if (!tok || depth > 16) throw new Error(`Unresolvable color token "${name}"`);
  let v = typeof tok.value === 'string' ? tok.value : tok.value[theme] ?? tok.value[themeIds[0]];
  const alias = /^\{(.+)\}$/.exec(v);
  return alias ? resolve(alias[1], theme, depth + 1) : v;
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const colors = {};
for (const theme of themeIds) {
  colors[theme] = {};
  for (const t of tokens.color.tokens) colors[theme][camel(t.name)] = resolve(t.name, theme);
}

// ---------------------------------------------------------------- lengths
const px = (v) => (typeof v === 'number' ? v : parseFloat(String(v)));
const family = (key) => Object.fromEntries(tokens[key].tokens.map((t) => [camel(t.name.replace(/^[a-z]+-/, '')), px(t.value)]));
const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [Number(t.name.split('-')[1]), px(t.value)]));
const radius = family('radius');
const size = Object.fromEntries(tokens.size.tokens.map((t) => [camel(t.name), px(t.value)]));

// ---------------------------------------------------------------- type
// Map (family, weight) to the face names registered by @expo-google-fonts.
const FACE = {
  display: { 600: 'BricolageGrotesque_600SemiBold', 700: 'BricolageGrotesque_700Bold', 800: 'BricolageGrotesque_800ExtraBold' },
  sans: { 400: 'Figtree_400Regular', 500: 'Figtree_500Medium', 600: 'Figtree_600SemiBold', 700: 'Figtree_700Bold' },
};
const type = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const fam = s.family || group.family;
    const weight = Number(s.fontWeight);
    const face = FACE[fam][weight];
    if (!face) throw new Error(`No ${fam} face for weight ${weight} (${s.name})`);
    const style = { fontFamily: face, fontSize: px(s.fontSize), lineHeight: px(s.lineHeight) };
    if (s.letterSpacing) {
      const ls = String(s.letterSpacing);
      style.letterSpacing = ls.endsWith('em') ? +(parseFloat(ls) * px(s.fontSize)).toFixed(2) : px(ls);
    }
    if (s.tabular) style.fontVariant = ['tabular-nums'];
    type[camel(s.name)] = style;
  }
}

const header = `// GENERATED by scripts/build-design.js from design/tokens.json. Do not edit.\n`;
const out =
  header +
  `export const colors = ${JSON.stringify(colors, null, 2)} as const;\n\n` +
  `export type ThemeName = keyof typeof colors;\n` +
  `export type ColorTokens = { [K in keyof (typeof colors)['${themeIds[0]}']]: string };\n\n` +
  `export const spacing = ${JSON.stringify(spacing)} as const;\n` +
  `export const radius = ${JSON.stringify(radius)} as const;\n` +
  `export const size = ${JSON.stringify(size)} as const;\n\n` +
  `export const type = ${JSON.stringify(type, null, 2)} as const;\n` +
  `export type TypeStyle = keyof typeof type;\n`;
fs.mkdirSync(path.join(root, 'src/theme'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/theme/tokens.ts'), out);

// ---------------------------------------------------------------- icons
// App icon name -> Bootstrap Icons file (the web app's set, same version).
const ICONS = {
  home: 'house-door', receipt: 'receipt', people: 'people', shield: 'shield-check',
  upload: 'cloud-arrow-up', qr: 'qr-code', back: 'chevron-left', forward: 'chevron-right',
  check: 'check-circle', alert: 'exclamation-triangle', clock: 'clock', wallet: 'wallet2',
  close: 'x-lg', more: 'three-dots', image: 'image', safe: 'safe2', cash: 'cash-coin',
  search: 'search', person: 'person-circle', logout: 'box-arrow-right', camera: 'camera',
  plus: 'plus-lg', envelope: 'envelope', transfer: 'arrow-left-right', bank: 'bank',
  checkLg: 'check-lg', exclaim: 'exclamation-lg', sendUp: 'box-arrow-up', chevronDown: 'chevron-down',
  arrowRight: 'arrow-right', zoom: 'zoom-in', hourglass: 'hourglass-split', badge: 'person-badge',
};
const iconData = {};
for (const [name, file] of Object.entries(ICONS)) {
  const svg = fs.readFileSync(path.join(root, 'node_modules/bootstrap-icons/icons', file + '.svg'), 'utf8');
  const paths = [...svg.matchAll(/<path([^>]*)\/?>/g)].map((m) => {
    const d = /\sd="([^"]+)"/.exec(m[1])[1];
    const rule = /fill-rule="([^"]+)"/.exec(m[1]);
    return rule ? { d, fillRule: rule[1] } : { d };
  });
  if (!paths.length) throw new Error(`No paths in ${file}.svg`);
  iconData[name] = paths;
}
fs.writeFileSync(
  path.join(root, 'src/components/ui/icon-data.ts'),
  header.replace('design/tokens.json', 'bootstrap-icons 1.11.3 (MIT)') +
    `export const iconData = ${JSON.stringify(iconData)} as const;\n` +
    `export type IconName = keyof typeof iconData;\n`
);

console.log(`tokens: ${themeIds.join('/')} · ${Object.keys(colors[themeIds[0]]).length} colors · ${Object.keys(type).length} type styles · ${Object.keys(iconData).length} icons`);
