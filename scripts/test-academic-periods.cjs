const ts = require('typescript');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const src = fs.readFileSync('lib/academic-periods.ts','utf8');
const js = ts.transpileModule(src,{ compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports_ = {};
new Function('exports','module',js)(exports_,{exports:exports_});
const {periodsFor,followingPeriod,isValidPeriod,configurationForYear}=exports_;
const ay='A.Y. 2026 - 2027';
const fy={ [ay]:{mode:'FullYear',includeSummer:false} };
assert.deepEqual(periodsFor(fy[ay]),['Full Year']);
assert.deepEqual(followingPeriod(ay,'Full Year',fy),{ay:'A.Y. 2027 - 2028',term:'Full Year'});
const tr={ [ay]:{mode:'Trimester',includeSummer:false} };
assert.deepEqual(followingPeriod(ay,'1st Trimester',tr),{ay,term:'2nd Trimester'});
assert.deepEqual(followingPeriod(ay,'3rd Trimester',tr),{ay:'A.Y. 2027 - 2028',term:'1st Trimester'});
const sem={ [ay]:{mode:'Semester',includeSummer:false} };
assert.deepEqual(followingPeriod(ay,'2nd Sem',sem),{ay:'A.Y. 2027 - 2028',term:'1st Sem'});
assert.deepEqual(followingPeriod(ay,'2nd Sem',{}),{ay:'A.Y. 2027 - 2028',term:'1st Sem'});
const withSummer = { [ay]:{mode:'Semester',includeSummer:true} };
assert.deepEqual(followingPeriod(ay,'2nd Sem',withSummer),{ay,term:'Summer'});
assert.equal(isValidPeriod(ay,'Summer',sem[ay]),false);
assert.equal(isValidPeriod(ay,'1st Trimester',tr[ay]),true);
assert.deepEqual(configurationForYear('A.Y. 2027 - 2028',fy),fy[ay]);
const switchNext={...tr,'A.Y. 2027 - 2028':{mode:'FullYear',includeSummer:false}};
assert.deepEqual(followingPeriod(ay,'3rd Trimester',switchNext),{ay:'A.Y. 2027 - 2028',term:'Full Year'});
assert.throws(()=>followingPeriod(ay,'Summer',fy),/not enabled/);
assert.throws(()=>followingPeriod('INVALID','Full Year',fy));
console.log('PASS: Full-Year, Semester, Summer, Trimester, cross-year calendar changes, and invalid-term guards (11 checks).');
